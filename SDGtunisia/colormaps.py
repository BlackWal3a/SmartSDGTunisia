# ================================
# GET COLORMAP
# ================================
def get_colormap(name: str):
    return COLORMAPS.get(name, COLORMAPS["grayscale"])


# ================================
# 🎨 APPLY COLORMAP (0–1 input)
# ================================
def apply_colormap(norm_data, cmap):
    """
    norm_data: float array in [0,1]
    cmap: list of (value, [r,g,b])
    """

    h, w = norm_data.shape
    rgb = np.zeros((h, w, 3), dtype=np.uint8)

    for i in range(len(cmap) - 1):

        v1, c1 = cmap[i]
        v2, c2 = cmap[i + 1]

        mask = (norm_data >= v1) & (norm_data <= v2)

        if not np.any(mask):
            continue

        t = (norm_data[mask] - v1) / (v2 - v1 + 1e-12)

        c1 = np.array(c1)
        c2 = np.array(c2)

        rgb[mask] = (c1 + (c2 - c1) * t[:, None]).astype(np.uint8)

    return rgb